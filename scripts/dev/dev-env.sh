#!/usr/bin/env bash
# The platform -> developer interface (docs/developer-interface.md): creates the
# dev test users (scripts/dev/test-users.sh) and writes ONE file outside both
# repositories, ${STATE_DIR}/developer.env (0600), with endpoints, CA and
# registry settings, test users and the PATHS of secret files (0600, under
# ${STATE_DIR}). Secret values are never written into developer.env itself.
#
#   scripts/dev/dev-env.sh dev        (make dev-env ENV=dev)
# shellcheck source=../lib/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/../lib/common.sh"
# shellcheck source=../lib/registry.sh
source "${REPO_ROOT}/scripts/lib/registry.sh"
load_env "${1:-${ENV:-}}"
require_cmd kubectl
[[ "$ENV" == "dev" ]] || die "the developer interface is for dev only"
kubectl get --raw /readyz >/dev/null 2>&1 || die "cluster not reachable with ${KUBECONFIG} (make cluster-up ENV=${ENV})"

"${REPO_ROOT}/scripts/dev/test-users.sh" "$ENV"
# shellcheck source=/dev/null
source "${REPO_ROOT}/environments/${ENV}/test-users.conf"
# test_user <groups>: the test user whose groups are exactly <groups>
test_user() {
  local e
  for e in "${TEST_USERS[@]}"; do [[ "${e#*=}" == "$1" ]] && { printf '%s' "${e%%=*}"; return 0; }; done
  die "environments/${ENV}/test-users.conf has no user with groups exactly '$1'"
}
analyst="$(test_user analyst)"; pii_reader="$(test_user analyst,pii-reader)"; auditor="$(test_user auditor)"
pwdir="${STATE_DIR}/test-users"
for u in "$analyst" "$pii_reader" "$auditor"; do [[ -s "${pwdir}/${u}" ]] || die "password file ${pwdir}/${u} missing"; done

sec="${STATE_DIR}/developer"
kubectl -n identity get secret oidc-client-trino -o jsonpath='{.data.client-secret}' | base64 -d \
  | write_secret_file "${sec}/oidc-trino-client-secret"
[[ -s "${sec}/oidc-trino-client-secret" ]] || die "secret identity/oidc-client-trino has no client-secret"
mkdir -p "${STATE_DIR}/pki"
kubectl -n platform-system get configmap platform-ca -o jsonpath='{.data.ca\.crt}' > "${STATE_DIR}/pki/platform-ca.crt.tmp"
mv "${STATE_DIR}/pki/platform-ca.crt.tmp" "${STATE_DIR}/pki/platform-ca.crt"

ns=orchestration
# The first deployment needs this file before stack 22 exists (the solution publishes its
# image with the registry settings below): the Dagster keys are fixed names, so write them
# anyway and only warn. make e2e needs the deployments.
for d in dagster-code-dagster-user-deployments-lakehouse dagster-dagster-webserver; do
  kubectl -n "$ns" get deploy "$d" >/dev/null 2>&1 \
    || warn "deployment ${ns}/${d} not found yet: enough for the solution's make publish; make e2e needs stack 22-orchestration (make deploy ENV=${ENV})"
done

# exactly the keys of the solution's platform contract (docs/developer-interface.md);
# plain KEY=value, values without spaces or quotes
out="${STATE_DIR}/developer.env"
{
  echo "# Boccob platform -> developer interface (docs/developer-interface.md in the IaC repository)."
  echo "# Generated by 'make dev-env ENV=${ENV}' on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not edit; do not commit."
  echo "BOCCOB_ENV=${ENV}"
  echo "BOCCOB_REGISTRY_HOST=${REGISTRY_HOST}"
  echo "BOCCOB_REGISTRY_CA_FILE=${REGISTRY_CA_FILE}"
  echo "BOCCOB_REGISTRY_USER=${REGISTRY_PUSH_USER}"
  echo "BOCCOB_REGISTRY_PASSWORD_FILE=$(registry_push_password_file)"
  echo "BOCCOB_KUBECONFIG=${KUBECONFIG}"
  echo "BOCCOB_DAGSTER_NAMESPACE=${ns}"
  echo "BOCCOB_CODE_LOCATION=deploy/dagster-code-dagster-user-deployments-lakehouse"
  echo "BOCCOB_CODE_LOCATION_NAME=lakehouse"
  echo "BOCCOB_DAGSTER_WEBSERVER=deploy/dagster-dagster-webserver"
  echo "BOCCOB_DAGSTER_WEBSERVER_CONTAINER=dagster"
  echo "BOCCOB_DAGSTER_GRAPHQL_URL=http://127.0.0.1:80/graphql"
  echo "BOCCOB_DAGSTER_URL=https://dagster.${BASE_DOMAIN}"
  echo "BOCCOB_CA_BUNDLE=${STATE_DIR}/pki/platform-ca.crt"
  echo "BOCCOB_TRINO_URL=https://trino.${BASE_DOMAIN}"
  echo "BOCCOB_KEYCLOAK_URL=https://keycloak.${BASE_DOMAIN}"
  echo "BOCCOB_KEYCLOAK_REALM=lakehouse"
  echo "BOCCOB_KEYCLOAK_CLIENT_ID=trino"
  echo "BOCCOB_KEYCLOAK_CLIENT_SECRET_FILE=${sec}/oidc-trino-client-secret"
  echo "BOCCOB_TEST_ANALYST_USER=${analyst}"
  echo "BOCCOB_TEST_ANALYST_PASSWORD_FILE=${pwdir}/${analyst}"
  echo "BOCCOB_TEST_PII_READER_USER=${pii_reader}"
  echo "BOCCOB_TEST_PII_READER_PASSWORD_FILE=${pwdir}/${pii_reader}"
  echo "BOCCOB_TEST_AUDITOR_USER=${auditor}"
  echo "BOCCOB_TEST_AUDITOR_PASSWORD_FILE=${pwdir}/${auditor}"
} | write_secret_file "$out"
rm -f "${sec}/trino-svc-dagster-password"   # no longer part of the interface
log "wrote ${out} (export BOCCOB_PLATFORM_ENV=${out} for the solution repository)"
