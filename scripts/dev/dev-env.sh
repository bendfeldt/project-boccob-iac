#!/usr/bin/env bash
# The platform -> developer interface (docs/developer-interface.md): creates the
# dev test users (scripts/dev/test-users.sh) and writes ONE file outside both
# repositories, ${STATE_DIR}/developer.env (0600), with endpoints, CA and
# registry settings, test users and the PATHS of secret files (0600, under
# ${STATE_DIR}). Secret values are never written into developer.env itself.
#
#   scripts/dev/dev-env.sh dev        (make dev-env ENV=dev)
# shellcheck source=../lib/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/../lib/common.sh"
# shellcheck source=../lib/registry.sh
source "${REPO_ROOT}/scripts/lib/registry.sh"
load_env "${1:-${ENV:-}}"
require_cmd kubectl
[[ "$ENV" == "dev" ]] || die "the developer interface is for dev only"
kubectl get --raw /readyz >/dev/null 2>&1 || die "cluster not reachable with ${KUBECONFIG} (make cluster-up ENV=${ENV})"

"${REPO_ROOT}/scripts/dev/test-users.sh" "$ENV"
# shellcheck source=/dev/null
source "${REPO_ROOT}/environments/${ENV}/test-users.conf"

sec="${STATE_DIR}/developer"
secret_to_file() { # secret_to_file <namespace> <secret> <key> <file>
  kubectl -n "$1" get secret "$2" -o jsonpath="{.data.${3//./\\.}}" | base64 -d | write_secret_file "$4"
  [[ -s "$4" ]] || die "secret ${1}/${2} has no key ${3}"
}
secret_to_file identity oidc-client-trino client-secret "${sec}/oidc-trino-client-secret"
secret_to_file query trino-sa-svc-dagster password "${sec}/trino-svc-dagster-password"
mkdir -p "${STATE_DIR}/pki"
kubectl -n platform-system get configmap platform-ca -o jsonpath='{.data.ca\.crt}' > "${STATE_DIR}/pki/platform-ca.crt.tmp"
mv "${STATE_DIR}/pki/platform-ca.crt.tmp" "${STATE_DIR}/pki/platform-ca.crt"

# public URLs are always on 443; BOCCOB_INGRESS_IP:PORT is where this machine reaches the ingress
out="${STATE_DIR}/developer.env"
{
  echo "# Boccob platform -> developer interface (docs/developer-interface.md in the IaC repository)."
  echo "# Generated by 'make dev-env ENV=${ENV}' on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not edit; do not commit."
  q() { printf "%s='%s'\n" "$1" "$2"; }
  q BOCCOB_INTERFACE_VERSION 1
  q BOCCOB_ENV "$ENV"
  q BOCCOB_PLATFORM_DIR "$REPO_ROOT"
  q BOCCOB_KUBECONFIG "$KUBECONFIG"
  q BOCCOB_BASE_DOMAIN "$BASE_DOMAIN"
  q BOCCOB_CA_BUNDLE "${STATE_DIR}/pki/platform-ca.crt"
  q BOCCOB_INGRESS_IP "${DEV_PUBLISH_ADDR:-127.0.0.1}"
  q BOCCOB_INGRESS_PORT "${DEV_HTTPS_PORT:-443}"
  q BOCCOB_NO_PROXY ".${BASE_DOMAIN#*.},${REGISTRY_HOST%%:*},localhost,127.0.0.1"
  for svc in trino keycloak polaris dagster s3 openbao; do
    q "BOCCOB_${svc^^}_URL" "https://${svc}.${BASE_DOMAIN}"
  done
  q BOCCOB_OIDC_ISSUER "https://keycloak.${BASE_DOMAIN}/realms/lakehouse"
  q BOCCOB_REGISTRY_HOST "$REGISTRY_HOST"
  q BOCCOB_REGISTRY_CA_FILE "$REGISTRY_CA_FILE"
  q BOCCOB_REGISTRY_NAMESPACE boccob
  q BOCCOB_REGISTRY_PUSH_USER "$REGISTRY_PUSH_USER"
  q BOCCOB_REGISTRY_PUSH_PASSWORD_FILE "$(registry_push_password_file)"
  q BOCCOB_CLUSTER_ARCH "$CLUSTER_ARCH"
  q BOCCOB_TEST_USERS "${TEST_USERS[*]}"
  q BOCCOB_TEST_USER_PASSWORD_DIR "${STATE_DIR}/test-users"
  q BOCCOB_OIDC_TEST_CLIENT trino
  q BOCCOB_OIDC_TEST_CLIENT_SECRET_FILE "${sec}/oidc-trino-client-secret"
  q BOCCOB_TRINO_SERVICE_USER svc-dagster
  q BOCCOB_TRINO_SERVICE_PASSWORD_FILE "${sec}/trino-svc-dagster-password"
} | write_secret_file "$out"
log "wrote ${out} (export BOCCOB_PLATFORM_ENV=${out} for the solution repository)"
