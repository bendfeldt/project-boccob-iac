#!/usr/bin/env bash
# Resolve versions.yaml -> versions.lock.yaml (digests + checksums).
# Needs internet (run on the connected workstation).
#
#   scripts/lock-update.sh            resolve everything
#   REUSE=1 scripts/lock-update.sh    keep entries whose source/tag/version/url are unchanged
# shellcheck source=lib/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib/common.sh"
require_cmd skopeo helm jq yq curl sha256sum

REUSE="${REUSE:-1}"
want="$(yq -c . "$VERSIONS_FILE")"
old='{}'
[[ -f "$LOCK_FILE" && "$REUSE" == "1" ]] && old="$(yq -c . "$LOCK_FILE")"

platform="$(jq -r '.platform' <<<"$want")"
os="${platform%%/*}"; arch="${platform##*/}"
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT

images='{}'
while read -r key; do
  src="$(jq -r --arg k "$key" '.images[$k].source' <<<"$want")"
  tag="$(jq -r --arg k "$key" '.images[$k].tag' <<<"$want")"
  groups="$(jq -c --arg k "$key" '.images[$k].groups // []' <<<"$want")"
  prev="$(jq -c --arg k "$key" '.images[$k] // {}' <<<"$old")"
  if [[ "$(jq -r '.source // ""' <<<"$prev")" == "$src" && "$(jq -r '.tag // ""' <<<"$prev")" == "$tag" \
        && "$(jq -r '.digest // ""' <<<"$prev")" == sha256:* ]]; then
    digest="$(jq -r '.digest' <<<"$prev")"; index_digest="$(jq -r '.index_digest // ""' <<<"$prev")"
  else
    log "resolve image ${src}:${tag}"
    skopeo inspect --raw "docker://${src}:${tag}" > "${tmp}/raw.json"
    top="sha256:$(sha256_of "${tmp}/raw.json")"
    if jq -e '.manifests' "${tmp}/raw.json" >/dev/null; then
      index_digest="$top"
      digest="$(jq -r --arg os "$os" --arg arch "$arch" \
        '[.manifests[] | select(.platform.os == $os and .platform.architecture == $arch)][0].digest // ""' "${tmp}/raw.json")"
      [[ -n "$digest" ]] || die "no ${platform} manifest in ${src}:${tag}"
    else
      index_digest=""; digest="$top"
    fi
  fi
  images="$(jq -c --arg k "$key" --arg s "$src" --arg t "$tag" --arg d "$digest" --arg i "$index_digest" --argjson g "$groups" \
    '.[$k] = ({source: $s, tag: $t, digest: $d, groups: $g} + (if $i != "" then {index_digest: $i} else {} end))' <<<"$images")"
done < <(jq -r '.images | keys_unsorted[]' <<<"$want")

charts='{}'
while read -r key; do
  repo="$(jq -r --arg k "$key" '.charts[$k].repo' <<<"$want")"
  name="$(jq -r --arg k "$key" '.charts[$k].name' <<<"$want")"
  ver="$(jq -r --arg k "$key" '.charts[$k].version' <<<"$want")"
  groups="$(jq -c --arg k "$key" '.charts[$k].groups // []' <<<"$want")"
  prev="$(jq -c --arg k "$key" '.charts[$k] // {}' <<<"$old")"
  if [[ "$(jq -r '"\(.repo)|\(.name)|\(.version)"' <<<"$prev")" == "${repo}|${name}|${ver}" \
        && -n "$(jq -r '.sha256 // ""' <<<"$prev")" ]]; then
    sum="$(jq -r '.sha256' <<<"$prev")"
  else
    log "resolve chart ${name} ${ver} (${repo})"
    rm -rf "${tmp}/chart"; mkdir -p "${tmp}/chart"
    if [[ "$repo" == oci://* ]]; then
      helm pull "${repo}/${name}" --version "$ver" -d "${tmp}/chart" >/dev/null
    else
      helm pull "$name" --repo "$repo" --version "$ver" -d "${tmp}/chart" >/dev/null
    fi
    sum="$(sha256_of "${tmp}/chart/"*.tgz)"
  fi
  charts="$(jq -c --arg k "$key" --arg r "$repo" --arg n "$name" --arg v "$ver" --arg s "$sum" --argjson g "$groups" \
    '.[$k] = {repo: $r, name: $n, version: $v, sha256: $s, groups: $g}' <<<"$charts")"
done < <(jq -r '.charts | keys_unsorted[]' <<<"$want")

binaries='{}'
while read -r key; do
  entry="$(jq -c --arg k "$key" '.binaries[$k]' <<<"$want")"
  url="$(jq -r '.url' <<<"$entry")"; file="$(jq -r '.file' <<<"$entry")"
  prev="$(jq -c --arg k "$key" '.binaries[$k] // {}' <<<"$old")"
  if [[ "$(jq -r '.url // ""' <<<"$prev")" == "$url" && -n "$(jq -r '.sha256 // ""' <<<"$prev")" ]]; then
    sum="$(jq -r '.sha256' <<<"$prev")"
  else
    dest="${BOCCOB_CACHE_DIR}/downloads/${key}/${file}"
    rm -f "$dest"
    fetch_verified "$url" "$dest" ""
    sum="$(sha256_of "$dest")"
  fi
  binaries="$(jq -c --arg k "$key" --arg s "$sum" --argjson e "$entry" '.[$k] = ($e + {sha256: $s})' <<<"$binaries")"
done < <(jq -r '.binaries | keys_unsorted[]' <<<"$want")

{
  cat <<'HDR'
# versions.lock.yaml — GENERATED by `make lock` from versions.yaml. Do not edit by hand.
# Single source of truth for every pinned image (linux/amd64 manifest digest),
# Helm chart (tgz sha256) and downloaded binary (sha256) used by this platform.
HDR
  jq -n --argjson w "$want" --argjson i "$images" --argjson c "$charts" --argjson b "$binaries" \
    '{platform: $w.platform, k3s: $w.k3s, images: $i, charts: $c, binaries: $b}' | yq -y .
} > "${LOCK_FILE}.tmp"
mv "${LOCK_FILE}.tmp" "$LOCK_FILE"
log "wrote ${LOCK_FILE}: $(jq 'length' <<<"$images") images, $(jq 'length' <<<"$charts") charts, $(jq 'length' <<<"$binaries") binaries"
