#!/usr/bin/env bash
# Build the k3s NODE bundle for test/prod hosts (air-gap install):
#   k3s binary, k3s-airgap-images tarball, upstream install.sh (all checksum
#   verified against versions.lock.yaml), hardening files, host-install.sh.
#
#   scripts/airgap/node-bundle.sh <env> [out-dir]     (connected machine, or
#   BUNDLE_DIR=<airgap bundle> to take the binaries from `make airgap-bundle`)
# shellcheck source=../lib/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/../lib/common.sh"
load_env "${1:-${ENV:-}}"
out="${2:-${BOCCOB_CACHE_DIR}/node-bundle-${ENV}}"
[[ -f "${REGISTRY_CA_FILE}" ]] || die "registry CA not found: ${REGISTRY_CA_FILE} (copy the CA of the ${ENV} Zot registry there)"

rm -rf "$out"; mkdir -p "${out}/lib" "${out}/hardening"
for key in k3s k3s-airgap-images k3s-install; do
  file="$(lock_q '.binaries[$k].file' --arg k "$key")"
  sum="$(lock_q '.binaries[$k].sha256' --arg k "$key")"
  if [[ -n "${BUNDLE_DIR:-}" && -f "${BUNDLE_DIR}/binaries/${file}" ]]; then
    cp "${BUNDLE_DIR}/binaries/${file}" "${out}/${file}"
    [[ "$(sha256_of "${out}/${file}")" == "$sum" ]] || die "checksum mismatch: ${file}"
  else
    fetch_verified "$(lock_q '.binaries[$k].url' --arg k "$key")" "${out}/${file}" "$sum"
  fi
done
cp "${REPO_ROOT}/scripts/cluster/host-install.sh" "${out}/"
cp "${REPO_ROOT}/scripts/lib/k3s-config.sh" "${out}/lib/"
cp "${REPO_ROOT}/scripts/cluster/config/audit-policy.yaml" "${REPO_ROOT}/scripts/cluster/config/admission.yaml" "${out}/hardening/"
cp "${REGISTRY_CA_FILE}" "${out}/hardening/registry-ca.crt"
cat > "${out}/bundle.env" <<ENVF
# generated by node-bundle.sh
K3S_VERSION="$(lock_q '.k3s.version')"
REGISTRY_HOST="${REGISTRY_HOST}"
K3S_API_ENDPOINT="${K3S_API_ENDPOINT:-}"
K3S_FLANNEL_BACKEND="${K3S_FLANNEL_BACKEND:-}"
ENVF
sums="$(cd "$out" && find . -type f ! -name SHA256SUMS -print0 | sort -z | xargs -0 sha256sum)"
printf '%s\n' "$sums" > "${out}/SHA256SUMS"
tar -C "$(dirname "$out")" -cf "${out}.tar" "$(basename "$out")"
log "node bundle: ${out}.tar ($(du -sh "${out}.tar" | awk '{print $1}')) — copy to every node and run host-install.sh"
