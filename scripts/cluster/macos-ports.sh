#!/usr/bin/env bash
# macOS only: pf (packet filter) redirect of the standard web ports on the loopback to
# the ports podman forwards from the machine:
#   127.0.0.1:443 -> 127.0.0.1:${DEV_HTTPS_PORT} (8443)    127.0.0.1:80 -> 127.0.0.1:${DEV_HTTP_PORT} (8080)
# so https://<svc>.dev.lakehouse.internal works without a port (the only public URL form).
#
#   macos-ports.sh <env> add|remove|check        (make macos-ports / macos-ports-remove; add/remove use sudo)
#
# Follows Apple's pf.conf / pfctl layout instead of replacing /etc/pf.conf:
#   - rules in a dedicated anchor file   /etc/pf.anchors/boccob
#   - /etc/pf.conf gets two marked lines (idempotent): `rdr-anchor "boccob"` right after
#     Apple's `rdr-anchor "com.apple/*"` (translation rules must precede filter rules) and
#     `load anchor "boccob" from "/etc/pf.anchors/boccob"` at the end; a backup is kept
#   - pf is enabled with a reference token (`pfctl -E`), kept in /etc/pf.anchors/boccob.token
#     and released with `pfctl -X` on remove, so other users of pf are not switched off
#   - a LaunchDaemon (/Library/LaunchDaemons/io.boccob.pf.plist) reloads /etc/pf.conf and
#     enables pf at boot (pf starts disabled on macOS)
# macOS updates may restore /etc/pf.conf: `make doctor` / `check` report it; run add again.
# shellcheck source=../lib/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/../lib/common.sh"
load_env "${1:-${ENV:-}}"
action="${2:-check}"
[[ "$(host_os)" == "darwin" ]] || { log "not macOS: nothing to do (Linux publishes 443/80 directly)"; exit 0; }

PF_CONF="${PF_CONF:-/etc/pf.conf}"
ANCHOR_NAME="boccob"
ANCHOR_FILE="${PF_ANCHOR_FILE:-/etc/pf.anchors/boccob}"
TOKEN_FILE="${ANCHOR_FILE}.token"
PLIST="${PF_PLIST:-/Library/LaunchDaemons/io.boccob.pf.plist}"
MARK="# boccob (managed by project-boccob-iac)"
https="${DEV_HTTPS_PORT:-8443}" http="${DEV_HTTP_PORT:-8080}"
[[ "$https" != "443" && "$http" != "80" ]] || die "DEV_HTTPS_PORT/DEV_HTTP_PORT are 443/80: nothing to redirect"
SUDO=(sudo); [[ "$(id -u)" == "0" ]] && SUDO=()

rules() {
  cat <<RULES
${MARK}: generated by scripts/cluster/macos-ports.sh, do not edit
rdr pass on lo0 inet proto tcp from any to 127.0.0.1 port 443 -> 127.0.0.1 port ${https}
rdr pass on lo0 inet proto tcp from any to 127.0.0.1 port 80 -> 127.0.0.1 port ${http}
RULES
}

plist() {
  cat <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>io.boccob.pf</string>
  <key>ProgramArguments</key>
  <array><string>/sbin/pfctl</string><string>-E</string><string>-f</string><string>${PF_CONF}</string></array>
  <key>RunAtLoad</key><true/>
</dict>
</plist>
PLIST
}

# pf_conf_with_anchor <in> : pf.conf with our two lines, existing ones removed first
pf_conf_with_anchor() {
  awk -v mark="$MARK" -v name="$ANCHOR_NAME" -v file="$ANCHOR_FILE" '
    index($0, mark) { next }
    { print }
    /^rdr-anchor "com\.apple\/\*"/ && !done { printf "rdr-anchor \"%s\" %s\n", name, mark; done = 1 }
    END {
      if (!done) printf "rdr-anchor \"%s\" %s\n", name, mark
      printf "load anchor \"%s\" from \"%s\" %s\n", name, file, mark
    }' "$1"
}
pf_conf_without_anchor() { awk -v mark="$MARK" 'index($0, mark) { next } { print }' "$1"; }

installed() {
  [[ -f "$ANCHOR_FILE" ]] && cmp -s <(rules) "$ANCHOR_FILE" \
    && grep -qF "rdr-anchor \"${ANCHOR_NAME}\"" "$PF_CONF" && grep -qF "load anchor \"${ANCHOR_NAME}\"" "$PF_CONF"
}
# active: needs root to read pf state; without a cached sudo, test the redirect itself
active() {
  local as_root=()
  [[ ${#SUDO[@]} -gt 0 ]] && as_root=(sudo -n)
  if [[ ${#SUDO[@]} -eq 0 ]] || sudo -n true 2>/dev/null; then
    "${as_root[@]}" pfctl -s info 2>/dev/null | grep -q '^Status: Enabled' \
      && "${as_root[@]}" pfctl -a "$ANCHOR_NAME" -s nat 2>/dev/null | grep -q "port = 443"
  else
    port_listening 127.0.0.1 443 && port_listening 127.0.0.1 "$https"
  fi
}

case "$action" in
  check)
    if ! installed; then warn "pf redirect not installed (make macos-ports ENV=${ENV})"; exit 1; fi
    if active; then log "pf redirect active: 127.0.0.1:443 -> ${https}, :80 -> ${http}"
    else warn "pf redirect installed but not active (make macos-ports ENV=${ENV} reloads it; is the cluster up?)"; exit 1; fi
    ;;
  add)
    require_cmd pfctl
    tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
    rules > "${tmp}/anchor"
    pf_conf_with_anchor "$PF_CONF" > "${tmp}/pf.conf"
    plist > "${tmp}/plist"
    "${SUDO[@]}" install -d -m 0755 "$(dirname "$ANCHOR_FILE")"
    "${SUDO[@]}" install -m 0644 "${tmp}/anchor" "$ANCHOR_FILE"
    "${SUDO[@]}" pfctl -n -a "$ANCHOR_NAME" -f "$ANCHOR_FILE" || die "pf rejected ${ANCHOR_FILE}"
    if ! cmp -s "${tmp}/pf.conf" "$PF_CONF"; then
      [[ -f "${PF_CONF}.boccob-backup" ]] || "${SUDO[@]}" cp -p "$PF_CONF" "${PF_CONF}.boccob-backup"
      "${SUDO[@]}" pfctl -n -f "${tmp}/pf.conf" || die "pf rejected the new ${PF_CONF} (unchanged)"
      "${SUDO[@]}" sh -c 'cat "$1" > "$2"' sh "${tmp}/pf.conf" "$PF_CONF"
      log "added the ${ANCHOR_NAME} anchor to ${PF_CONF} (backup: ${PF_CONF}.boccob-backup)"
    fi
    "${SUDO[@]}" pfctl -f "$PF_CONF" 2>/dev/null || die "pfctl -f ${PF_CONF} failed"
    if [[ ! -s "$TOKEN_FILE" ]]; then
      token="$("${SUDO[@]}" pfctl -E 2>&1 | sed -n 's/^Token : //p')"
      [[ -n "$token" ]] && printf '%s\n' "$token" | "${SUDO[@]}" tee "$TOKEN_FILE" >/dev/null
    fi
    if ! cmp -s "${tmp}/plist" "$PLIST" 2>/dev/null; then
      "${SUDO[@]}" install -m 0644 "${tmp}/plist" "$PLIST"
      "${SUDO[@]}" launchctl bootout system "$PLIST" 2>/dev/null || true
      "${SUDO[@]}" launchctl bootstrap system "$PLIST" || warn "launchctl bootstrap failed: the redirect will not come back after a reboot"
    fi
    log "pf redirect: 127.0.0.1:443 -> ${https}, 127.0.0.1:80 -> ${http} (remove: make macos-ports-remove ENV=${ENV})"
    ;;
  remove)
    require_cmd pfctl
    if [[ -f "$PLIST" ]]; then
      "${SUDO[@]}" launchctl bootout system "$PLIST" 2>/dev/null || true
      "${SUDO[@]}" rm -f "$PLIST"
    fi
    if grep -qF "$MARK" "$PF_CONF"; then
      tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT
      pf_conf_without_anchor "$PF_CONF" > "$tmp"
      "${SUDO[@]}" sh -c 'cat "$1" > "$2"' sh "$tmp" "$PF_CONF"
    fi
    "${SUDO[@]}" pfctl -a "$ANCHOR_NAME" -F all 2>/dev/null || true
    "${SUDO[@]}" pfctl -f "$PF_CONF" 2>/dev/null || true
    if [[ -s "$TOKEN_FILE" ]]; then
      "${SUDO[@]}" pfctl -X "$(cat "$TOKEN_FILE")" 2>/dev/null || true   # release our enable reference only
    fi
    "${SUDO[@]}" rm -f "$ANCHOR_FILE" "$TOKEN_FILE"
    log "pf redirect removed"
    ;;
  *) die "usage: macos-ports.sh <env> add|remove|check" ;;
esac
