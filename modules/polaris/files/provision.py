"""Idempotent provisioning of Apache Polaris through its management API.

Desired state: /config/desired.json (catalogs, principals, grants).
Root credentials: environment POLARIS_ROOT_CLIENT_ID / POLARIS_ROOT_CLIENT_SECRET.
Principal credentials are generated by Polaris; they are written to OpenBao KV v2
(kubernetes auth with the pod's ServiceAccount) and never logged.
Python standard library only.
"""

import json
import os
import ssl
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

CA = os.environ.get("CA_BUNDLE", "/etc/platform-ca/ca.crt")
CTX = ssl.create_default_context(cafile=CA)
POLARIS = os.environ["POLARIS_URL"].rstrip("/")
REALM = os.environ.get("POLARIS_REALM", "POLARIS")
BAO = os.environ["OPENBAO_URL"].rstrip("/")
BAO_ROLE = os.environ["OPENBAO_ROLE"]
BAO_MOUNT = os.environ.get("OPENBAO_KV_MOUNT", "kv")
KV_PREFIX = os.environ["KV_PREFIX"].strip("/")
MGMT = f"{POLARIS}/api/management/v1"
TOKEN_URL = f"{POLARIS}/api/catalog/v1/oauth/tokens"


def log(msg):
    print(msg, flush=True)


def http(method, url, body=None, headers=None, form=None, ok=(200, 201, 204)):
    data = None
    hdrs = {"Accept": "application/json", "Polaris-Realm": REALM}
    hdrs.update(headers or {})
    if form is not None:
        data = urllib.parse.urlencode(form).encode()
        hdrs["Content-Type"] = "application/x-www-form-urlencoded"
    elif body is not None:
        data = json.dumps(body).encode()
        hdrs["Content-Type"] = "application/json"
    req = urllib.request.Request(url, data=data, method=method, headers=hdrs)
    try:
        with urllib.request.urlopen(req, context=CTX, timeout=30) as resp:
            raw = resp.read()
            return resp.status, (json.loads(raw) if raw else None)
    except urllib.error.HTTPError as e:
        raw = e.read()
        if e.code in ok:
            return e.code, (json.loads(raw) if raw else None)
        try:
            payload = json.loads(raw)
        except ValueError:
            payload = {"raw": raw[:300].decode(errors="replace")}
        return e.code, payload


def polaris_token(client_id, client_secret):
    code, body = http(
        "POST",
        TOKEN_URL,
        form={
            "grant_type": "client_credentials",
            "client_id": client_id,
            "client_secret": client_secret,
            "scope": "PRINCIPAL_ROLE:ALL",
        },
    )
    return body.get("access_token") if code == 200 and body else None


class Polaris:
    def __init__(self, token):
        self.h = {"Authorization": f"Bearer {token}"}

    def call(self, method, path, body=None, allow=()):
        code, payload = http(method, f"{MGMT}{path}", body=body, headers=self.h)
        if code not in (200, 201, 204) and code not in allow:
            raise RuntimeError(f"{method} {path} -> {code}: {json.dumps(payload)[:400]}")
        return code, payload


class Bao:
    def __init__(self):
        with open("/var/run/secrets/kubernetes.io/serviceaccount/token") as f:
            jwt = f.read().strip()
        code, body = http("POST", f"{BAO}/v1/auth/kubernetes/login", body={"role": BAO_ROLE, "jwt": jwt})
        if code != 200:
            raise RuntimeError(f"OpenBao login failed: {code}")
        self.h = {"X-Vault-Token": body["auth"]["client_token"]}

    def read(self, path):
        code, body = http("GET", f"{BAO}/v1/{BAO_MOUNT}/data/{path}", headers=self.h)
        if code == 404:
            return None
        if code != 200:
            raise RuntimeError(f"OpenBao read {path}: {code}")
        return body["data"]["data"]

    def write(self, path, data):
        code, _ = http("POST", f"{BAO}/v1/{BAO_MOUNT}/data/{path}", body={"data": data}, headers=self.h)
        if code not in (200, 204):
            raise RuntimeError(f"OpenBao write {path}: {code}")


def ensure_catalog(p, name, spec):
    want_props = dict(spec.get("properties", {}))
    want_props["default-base-location"] = spec["base_location"]
    storage = {
        "storageType": "S3",
        "allowedLocations": spec["allowed_locations"],
        "endpoint": spec["endpoint"],
        "endpointInternal": spec.get("endpoint_internal", spec["endpoint"]),
        "pathStyleAccess": True,
        "stsUnavailable": True,
        "region": spec["region"],
    }
    code, cur = p.call("GET", f"/catalogs/{name}", allow=(404,))
    if code == 404:
        p.call(
            "POST",
            "/catalogs",
            {"catalog": {"name": name, "type": "INTERNAL", "properties": want_props, "storageConfigInfo": storage}},
        )
        log(f"catalog {name}: created")
        return
    have_props = cur.get("properties", {})
    have_storage = cur.get("storageConfigInfo", {})
    drift = any(have_props.get(k) != v for k, v in want_props.items()) or any(
        have_storage.get(k) != v for k, v in storage.items()
    )
    if drift:
        merged = dict(have_props)
        merged.update(want_props)
        p.call(
            "PUT",
            f"/catalogs/{name}",
            {"currentEntityVersion": cur["entityVersion"], "properties": merged, "storageConfigInfo": storage},
        )
        log(f"catalog {name}: updated")
    else:
        log(f"catalog {name}: up to date")


def ensure_principal(p, bao, name, spec):
    kv_path = f"{KV_PREFIX}/{name}"
    creds = None
    code, _ = p.call("GET", f"/principals/{name}", allow=(404,))
    if code == 404:
        _, body = p.call("POST", "/principals", {"principal": {"name": name, "properties": {}}})
        creds = body["credentials"]
        log(f"principal {name}: created")
    else:
        stored = bao.read(kv_path)
        if stored and polaris_token(stored.get("client-id", ""), stored.get("client-secret", "")):
            log(f"principal {name}: exists, stored credentials are valid")
        else:
            _, body = p.call("POST", f"/principals/{name}/rotate")
            creds = body["credentials"]
            log(f"principal {name}: credentials rotated (none or invalid in OpenBao)")
    if creds:
        bao.write(
            kv_path,
            {
                "client-id": creds["clientId"],
                "client-secret": creds["clientSecret"],
                "credential": f"{creds['clientId']}:{creds['clientSecret']}",
                "scope": "PRINCIPAL_ROLE:ALL",
                "principal": name,
            },
        )
        log(f"principal {name}: credentials stored in OpenBao at {BAO_MOUNT}/{kv_path}")

    role = spec.get("principal_role", name)
    p.call("POST", "/principal-roles", {"principalRole": {"name": role}}, allow=(409,))
    p.call("PUT", f"/principals/{name}/principal-roles", {"principalRole": {"name": role}}, allow=(409,))
    for catalog, privileges in spec.get("catalog_privileges", {}).items():
        crole = spec.get("catalog_role", f"{name}_access")
        p.call("POST", f"/catalogs/{catalog}/catalog-roles", {"catalogRole": {"name": crole}}, allow=(409,))
        _, grants = p.call("GET", f"/catalogs/{catalog}/catalog-roles/{crole}/grants")
        have = {g["privilege"] for g in (grants or {}).get("grants", []) if g.get("type") == "catalog"}
        for priv in sorted(set(privileges) - have):
            p.call(
                "PUT",
                f"/catalogs/{catalog}/catalog-roles/{crole}/grants",
                {"grant": {"type": "catalog", "privilege": priv}},
            )
        for priv in sorted(have - set(privileges)):
            p.call(
                "POST",
                f"/catalogs/{catalog}/catalog-roles/{crole}/grants",
                {"grant": {"type": "catalog", "privilege": priv}},
            )
        p.call("PUT", f"/principal-roles/{role}/catalog-roles/{catalog}", {"catalogRole": {"name": crole}}, allow=(409,))
        log(f"principal {name}: role {role} -> {catalog}.{crole} {sorted(privileges)}")


def main():
    with open("/config/desired.json") as f:
        desired = json.load(f)
    token = None
    for attempt in range(90):
        try:
            token = polaris_token(os.environ["POLARIS_ROOT_CLIENT_ID"], os.environ["POLARIS_ROOT_CLIENT_SECRET"])
        except (urllib.error.URLError, OSError) as e:
            log(f"waiting for Polaris ({e.__class__.__name__})")
        if token:
            break
        time.sleep(4)
    if not token:
        log("could not obtain a root token from Polaris")
        return 1
    p = Polaris(token)
    bao = Bao()
    for name, spec in desired["catalogs"].items():
        ensure_catalog(p, name, spec)
    for name, spec in desired["principals"].items():
        ensure_principal(p, bao, name, spec)
    log("polaris provisioning finished")
    return 0


if __name__ == "__main__":
    sys.exit(main())
